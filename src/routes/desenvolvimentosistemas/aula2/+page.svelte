<h2>Evolução e Integração de Sistemas</h2>

<Audios modulo="M10" aulas={["05", "06", "07", "08"]} />

<p>
  O cenário atual dos sistemas de informação é marcado pela integração entre
  dispositivos móveis, negócios eletrônicos (e-business) e comércio eletrônico
  (e-commerce). Essa convergência exige estruturas dinâmicas e seguras,
  impulsionadas pelo uso de <strong>recursos em nuvem</strong>, que reduzem
  custos de armazenamento e agilizam a transferência de dados. O foco das
  empresas é integrar sistemas a aplicativos móveis para ganhar agilidade,
  reduzir custos operacionais e aumentar a receita.
</p>

<h3>Classificação dos Sistemas de Informação</h3>

<p>
  Os sistemas são categorizados conforme sua abrangência e função dentro da
  hierarquia organizacional:
</p>

<ul>
  <li>
    <strong>SPT (Sistemas de Processamento de Transações):</strong> Focam em tarefas
    operacionais e rotinas específicas, como emissão de notas fiscais ou folha de
    pagamento.
  </li>
  <li>
    <strong>SIG (Sistemas de Informação Gerencial):</strong> Resultam da interligação
    de vários SPTs. Eles consolidam dados para fornecer uma visão mais ampla e apoiar
    o gerenciamento de áreas específicas.
  </li>
  <li>
    <strong>ERP (Enterprise Resource Planning):</strong> Sistemas integrados de gestão
    que utilizam uma base de dados única para todas as áreas da empresa. O ERP elimina
    a redundância de dados e conecta módulos fundamentais (Vendas, Finanças, RH,
    etc.) em uma só plataforma.
  </li>
</ul>

<h3>Aplicações Estratégicas e Gestão</h3>

<p>
  Além do ERP, existem aplicações especialistas que ampliam a capacidade de
  gestão e relacionamento da organização:
</p>

<ul>
  <li>
    <strong>SCM (Supply Chain Management):</strong> Gere a cadeia de suprimentos,
    integrando desde fornecedores de matéria-prima até a entrega do produto ao consumidor
    final. É frequentemente um sistema interorganizacional.
  </li>
  <li>
    <strong>CRM (Customer Relationship Management):</strong> Foca na gestão do relacionamento
    com o cliente. Monitora dados e comportamentos para prever demandas, personalizar
    o marketing e aumentar a fidelização.
  </li>
  <li>
    <strong>SGC (Sistemas de Gestão do Conhecimento):</strong> Gerenciam informações
    estruturadas e não estruturadas (vídeos, e-mails, conhecimento tácito). Servem
    para criar e distribuir o capital intelectual da empresa.
  </li>
  <li>
    <strong>BI (Business Intelligence):</strong> Ferramenta de suporte à decisão
    que utiliza gráficos e dashboards para resumir indicadores de desempenho.
  </li>
  <li>
    <strong>IA (Inteligência Artificial):</strong> Recurso que simula o comportamento
    humano para otimizar processos e análises dentro dos sistemas de gestão.
  </li>
</ul>

<h3>Diferenciação entre E-business e E-commerce</h3>

<p>
  Embora frequentemente usados como sinônimos, possuem abrangências distintas
  dentro do ambiente digital:
</p>

<ul>
  <li>
    <strong>E-business (Negócios Eletrônicos):</strong> É o conceito mais amplo.
    Envolve todos os processos de negócio realizados eletronicamente, incluindo comunicações
    e transações entre empresas, fornecedores, parceiros, funcionários e governo.
  </li>
  <li>
    <strong>E-commerce (Comércio Eletrônico):</strong> É uma subcategoria do e-business.
    Refere-se especificamente à compra e venda de bens e serviços através da internet,
    focando na transação comercial e no fechamento da venda.
  </li>
</ul>

<h3>Modelos de Negócios Eletrônicos</h3>

<p>
  As transações digitais são classificadas de acordo com os agentes envolvidos
  (quem vende/provê e quem compra/consome). A sigla utiliza o número 2 (do
  inglês two, com som de to, que significa "para"):
</p>

<h4>Identificação dos Agentes:</h4>

<ul>
  <li><strong>B (Business):</strong> Empresa / Negócio.</li>
  <li><strong>C (Consumer):</strong> Consumidor / Cliente final.</li>
  <li><strong>G (Government):</strong> Governo / Administração Pública.</li>
  <li><strong>E (Employee):</strong> Empregado / Colaborador.</li>
</ul>

<h4>Principais Modalidades:</h4>

<ul>
  <li>
    <strong>B2C (Business to Consumer):</strong> Venda direta da empresa para o consumidor
    final (ex: lojas virtuais de varejo).
  </li>
  <li>
    <strong>B2B (Business to Business):</strong> Transações comerciais entre empresas
    (ex: fabricante vendendo para um distribuidor).
  </li>
  <li>
    <strong>C2C (Consumer to Consumer):</strong> Transações entre consumidores (ex:
    sites de desapego ou leilões entre pessoas físicas).
  </li>
  <li>
    <strong>G2C / G2B (Government to...):</strong> Serviços do governo para cidadãos
    (pagamento de impostos) ou para empresas (licitações).
  </li>
  <li>
    <strong>B2E (Business to Employee):</strong> Processos internos da empresa para
    seus funcionários (ex: portal de RH ou treinamentos).
  </li>
</ul>

<p>
  O entendimento desses modelos é fundamental para desenhar a arquitetura dos
  sistemas de informação, pois cada relação demanda fluxos, seguranças e
  interfaces específicas.
</p>

<h3>Impacto e Relevância dos Aplicativos Mobile</h3>

<p>
  A migração do acesso de desktops para dispositivos móveis acelerou as
  transações eletrônicas devido à portabilidade e conveniência. Embora os sites
  funcionem em navegadores móveis, os aplicativos dedicados oferecem vantagens
  técnicas e estratégicas superiores.
</p>

<ul>
  <li>
    <strong>Vantagens Técnicas:</strong> Aplicativos bem desenvolvidos reduzem o
    tráfego de dados (economizando o plano do usuário), operam com maior velocidade,
    enviam notificações em tempo real e permitem a coleta de dados de uso para melhoria
    do sistema.
  </li>
  <li>
    <strong>Vantagens de Marketing:</strong> Funcionam como ferramentas de coleta
    de informações sobre o comportamento do consumidor e como canais diretos para
    ações promocionais personalizadas, incentivando novos negócios.
  </li>
</ul>

<h4>Aplicações Práticas nos Negócios</h4>

<p>
  O uso de aplicativos móveis ultrapassa a relação de venda com o cliente final,
  sendo ferramentas essenciais para a eficiência interna das empresas:
</p>

<ul>
  <li>
    <strong>Controle de Produção:</strong> Uso de tablets em linhas de montagem para
    coleta de dados em tempo real e monitoramento de processos.
  </li>
  <li>
    <strong>Força de Vendas Externa:</strong> Vendedores podem consultar estoques,
    verificar preços atualizados e transmitir pedidos instantaneamente de qualquer
    local.
  </li>
  <li>
    <strong>Monitoramento de Mercado:</strong> Facilidade para registrar e encaminhar
    dados sobre a concorrência e atividades de clientes em campo.
  </li>
</ul>

<p>
  A mobilidade, portanto, não é apenas um novo canal de acesso, mas uma
  estrutura que permite dinamismo, redução de custos operacionais e maior
  precisão na gestão da informação.
</p>

<h3>Computação em Nuvem (Cloud Computing)</h3>

<p>
  A computação em nuvem é um modelo de fornecimento de recursos de TI via
  internet que substitui a necessidade de infraestrutura local física. Ele
  permite o acesso a servidores, armazenamento, bancos de dados e softwares de
  forma remota e especializada.
</p>

<ul>
  <li>
    <strong>Modelo sob demanda:</strong> A organização contrata apenas o que utiliza,
    podendo ampliar ou reduzir os recursos (escalabilidade) com facilidade, conforme
    a necessidade do momento.
  </li>
  <li>
    <strong>Infraestrutura Híbrida:</strong> Modelo que combina o uso de nuvem com
    infraestrutura local. É comum em grandes empresas que possuem alta demanda de
    processamento interno mas buscam a flexibilidade da nuvem para certas operações.
  </li>
</ul>

<h4>Benefícios e Comparativo de Custos</h4>

<p>
  A decisão entre manter uma infraestrutura própria ou migrar para a nuvem
  envolve uma análise estratégica de custos e benefícios:
</p>

<ul>
  <li>
    <strong>Infraestrutura Própria:</strong> Exige alto investimento inicial para
    aquisição de hardware e software, além de gastos contínuos com manutenção, segurança
    física e equipes grandes de TI.
  </li>
  <li>
    <strong>Serviços em Nuvem:</strong> O investimento inicial é reduzido, transformando
    custos fixos em despesas operacionais variáveis de acordo com a demanda.
  </li>
  <li>
    <strong>Vantagens Principais:</strong>
    <ul>
      <li>
        <strong>Segurança e Atualização:</strong> Provedores especializados garantem
        atualizações tecnológicas e de segurança mais rápidas.
      </li>
      <li>
        <strong>Disponibilidade e Backup:</strong> Maior facilidade na recuperação
        de dados e garantia de que o sistema permanecerá online.
      </li>
      <li>
        <strong>Mobilidade:</strong> Acesso aos sistemas e dados de qualquer lugar,
        essencial para empresas que operam de forma dinâmica.
      </li>
      <li>
        <strong>Foco no Negócio:</strong> Permite reduzir a equipe interna de TI
        a um nível mínimo, focando em gestão e não apenas em manutenção de máquinas.
      </li>
    </ul>
  </li>
</ul>

<h3>Transformação Digital e Globalização</h3>

<p>
  A internet eliminou fronteiras geográficas, criando um mercado globalizado
  onde a informação circula instantaneamente. No entanto, essa mesma velocidade
  que cria oportunidades também torna modelos de negócios tradicionais obsoletos
  rapidamente. O desafio central é a adaptação contínua às mudanças tecnológicas
  para garantir a sobrevivência e a competitividade da organização.
</p>

<h4>Big Data e Internet das Coisas (IoT)</h4>

<p>
  O volume de dados gerados cresce de forma exponencial, impulsionado pela
  conexão de novos dispositivos:
</p>

<ul>
  <li>
    <strong>IoT (Internet das Coisas):</strong> Além de computadores e smartphones,
    diversos objetos cotidianos estão conectados à rede, gerando um fluxo constante
    de novos dados.
  </li>
  <li>
    <strong>Big Data:</strong> Refere-se a essa massa gigantesca de dados coletados.
    O desafio não é apenas armazenar, mas processar e transmitir esse volume com
    eficiência.
  </li>
  <li>
    <strong>Data Mining (Mineração de Dados):</strong> Técnica essencial para explorar
    grandes bases de dados, buscando padrões e regras que seriam invisíveis em análises
    simples.
  </li>
</ul>

<h4>Inteligência Artificial e Tomada de Decisão</h4>

<p>
  Com o custo elevado para manter grandes volumes de dados, as organizações
  precisam transformar dados brutos em inteligência estratégica.
</p>

<ul>
  <li>
    <strong>IA e Análise:</strong> O uso de Inteligência Artificial torna-se indispensável
    para analisar o Big Data e extrair informações que suportem decisões precisas.
  </li>
  <li>
    <strong>Retorno sobre Investimento:</strong> Sistemas de informação eficazes
    devem ser capazes de converter dados em novas oportunidades de negócio.
  </li>
  <li>
    <strong>Foco do Desenvolvedor:</strong> Profissionais da área devem focar na
    criação de meios dinâmicos para capturar e transformar dados em informações úteis,
    acompanhando a evolução constante das plataformas tecnológicas.
  </li>
</ul>

<h3>Visão Integrada dos Sistemas de Informação</h3>

<p>
  O desenvolvimento de sistemas não deve ser visto de forma isolada, mas como um
  ecossistema onde todos os elementos estão interligados. A eficácia de um
  sistema depende da harmonia entre a aplicação prática, a infraestrutura
  escolhida e o mercado em que atua.
</p>

<ul>
  <li>
    <strong>Ciclo de Valor:</strong> O mercado dinâmico e globalizado exige adaptação
    constante. Para atender a essa demanda, a infraestrutura (como a computação em
    nuvem) deve garantir que os dados estejam disponíveis e seguros.
  </li>
  <li>
    <strong>Dados e Mobilidade:</strong> Dispositivos móveis e IoT expandem as funcionalidades
    dos sistemas, atuando tanto na coleta massiva de dados quanto na entrega de informações
    personalizadas ao usuário final.
  </li>
  <li>
    <strong>Conhecimento Organizacional:</strong> Os negócios eletrônicos e o e-commerce
    conectam a ponta final (cliente) a todos os processos internos da empresa. Sistemas
    que coletam dados em diversos setores alimentam os softwares de gestão do conhecimento,
    transformando dados brutos em inteligência estratégica.
  </li>
</ul>

<h4>Planejamento e Desenvolvimento</h4>

<p>
  Ao planejar, analisar ou diagramar um sistema, é fundamental responder a
  perguntas estruturais que definem sua arquitetura:
</p>

<ul>
  <li>
    <strong>Aplicação Real:</strong> Qual problema o sistema resolve e qual sua função
    prática na organização?
  </li>
  <li>
    <strong>Público-Alvo:</strong> Quem são os usuários e quais são suas necessidades
    específicas?
  </li>
  <li>
    <strong>Escalabilidade:</strong> Quais são todas as possibilidades de expansão
    e uso futuro dessa ferramenta?
  </li>
  <li>
    <strong>Contexto Técnico:</strong> Como o sistema se integrará aos demais processos
    de e-business e à infraestrutura disponível?
  </li>
</ul>

<p>
  Esses elementos formam a base necessária para avançar nos estudos de
  engenharia de software e análise de sistemas.
</p>
