<h2>Fundamentos e Planejamento de Sistemas</h2>

<Audios modulo="M12" aulas={["01", "02", "03", "04"]} />

<p>
  O desenvolvimento de sistemas de informação exige um planejamento rigoroso e
  estruturado. Este processo garante que o sistema cumpra sua função, opere de
  forma segura e direta, e ofereça agilidade ao usuário final. O planejamento
  deve considerar não apenas a lógica de funcionamento, mas também as demandas
  de infraestrutura e a segurança dos dados para mitigar vulnerabilidades em
  transações.
</p>

<h3>Teoria Geral de Sistemas (TGS)</h3>

<p>
  A base do desenvolvimento de software reside na Teoria Geral de Sistemas,
  formulada pelo biólogo Ludwig Von Bertalanffy. Embora originada na biologia,
  sua lógica é aplicada na cibernética para compreender sistemas informatizados.
  A premissa central é que qualquer sistema opera sob um fluxo contínuo de
  entrada, processamento e saída.
</p>

<h3>Componentes do Fluxo Sistêmico</h3>

<p>
  Para que um sistema de informação seja eficaz, ele deve integrar seis
  elementos fundamentais:
</p>

<ul>
  <li>
    <strong>Objetivo:</strong> A finalidade central e a razão pela qual o sistema
    foi criado.
  </li>
  <li>
    <strong>Entradas:</strong> A matéria-prima necessária (dados, energia ou materiais)
    para iniciar o processo.
  </li>
  <li>
    <strong>Processamento:</strong> A etapa de transformação das entradas em algo
    novo.
  </li>
  <li>
    <strong>Saídas:</strong> O resultado final do processamento (produtos, serviços
    ou informações), que deve estar alinhado ao objetivo.
  </li>
  <li>
    <strong>Controles e Avaliações:</strong> Mecanismos de verificação para garantir
    que o fluxo esteja coerente com as metas estabelecidas.
  </li>
  <li>
    <strong>Retroalimentação (Feedback):</strong> Instrumento que utiliza dados da
    saída para retornar à entrada, validando e garantindo que a finalidade do sistema
    seja atingida.
  </li>
</ul>

<h3>Estrutura dos Sistemas Informatizados</h3>

<p>
  Na tecnologia da informação, a lógica sistêmica é executada através da
  interação entre <strong>hardware</strong> (componentes físicos/equipamentos) e
  <strong>software</strong>
  (instruções lógicas e aplicativos). Esse conjunto, apoiado por bancos de dados
  e infraestrutura de redes, visa transformar dados brutos em informações estruturadas.
  O objetivo final é percorrer a pirâmide do conhecimento, integrando dados, informação
  e inteligência para o suporte à decisão.
</p>

<h3>Dimensões dos Sistemas de Informação</h3>

<p>
  Um sistema de informação não se limita a tecnologia; ele é composto por três
  pilares fundamentais que devem atuar em conjunto:
</p>

<ul>
  <li>
    <strong>Dimensão Humana:</strong> Focada nas pessoas que interagem com o sistema.
    Envolve o treinamento dos usuários, as atitudes profissionais e o comportamento
    dos gestores.
  </li>
  <li>
    <strong>Dimensão Organizacional:</strong> Refere-se à estrutura da empresa. Inclui
    a hierarquia, as especializações de cada setor, os processos internos, a cultura
    organizacional e as influências políticas.
  </li>
  <li>
    <strong>Dimensão Tecnológica:</strong> É a infraestrutura física e lógica. Abrange
    o hardware, softwares, tecnologias de administração de dados, redes, telecomunicações
    e internet.
  </li>
</ul>

<h3>Fluxo de Funções do Sistema</h3>

<p>
  A aplicação dos conceitos de sistemas no ambiente organizacional segue um
  fluxo lógico de transformação de dados:
</p>

<ul>
  <li>
    <strong>Entrada:</strong> Coleta ou captura de dados brutos, que podem vir de
    fontes internas da empresa ou do ambiente externo.
  </li>
  <li>
    <strong>Processamento:</strong> Conversão e organização desses dados brutos para
    que adquiram um significado útil.
  </li>
  <li>
    <strong>Saída:</strong> Distribuição da informação já processada para as pessoas
    ou departamentos que as utilizarão em suas atividades.
  </li>
  <li>
    <strong>Feedback (Retroalimentação):</strong> Retorno da informação para membros
    específicos da organização. Serve para avaliar se o objetivo foi atingido e corrigir
    possíveis falhas na etapa de entrada ou processamento.
  </li>
</ul>

<h3>Abrangência dos Sistemas de Informação</h3>

<p>
  Os sistemas podem ser categorizados pela sua escala de atuação e integração de
  dados:
</p>

<ul>
  <li>
    <strong>Sistemas Departamentais:</strong> Atendem demandas exclusivas de um único
    departamento. Possuem bancos de dados isolados, o que dificulta o compartilhamento
    de informações com o restante da empresa.
  </li>
  <li>
    <strong>Sistemas Integrados (ERP):</strong> Unificam todas as áreas da organização
    (finanças, RH, vendas, etc.) em um único sistema. Utilizam módulos específicos
    que compartilham o mesmo banco de dados, facilitando o fluxo de informação.
  </li>
  <li>
    <strong>Sistemas Interorganizacionais:</strong> Operam integrando duas ou mais
    empresas diferentes, permitindo o compartilhamento de informações além das fronteiras
    da organização.
  </li>
</ul>

<h3>Sistemas por Níveis Organizacionais e Decisórios</h3>

<p>
  O tipo de sistema varia conforme a complexidade das decisões e o nível
  hierárquico:
</p>

<ul>
  <li>
    <strong
      >Nível Operacional (SPTs - Sistemas de Processamento de Transações):</strong
    > Focam em atividades rotineiras, repetitivas e estruturadas. Servem para aumentar
    a produtividade e o controle de dados básicos por funcionários administrativos
    e supervisores.
  </li>
  <li>
    <strong
      >Nível Tático ou Gerencial (SIGs - Sistemas de Informações Gerenciais):</strong
    > Dão suporte aos gerentes para o acompanhamento de metas e controle de departamentos.
    Transformam dados operacionais em resumos que auxiliam no monitoramento do desempenho.
  </li>
  <li>
    <strong
      >Nível Estratégico (SADs e SAEs - Apoio à Decisão e Executivos):</strong
    > Prestam suporte à alta diretoria. Fornecem informações sintetizadas, gráficos
    e indicadores de mercado para decisões de alta complexidade e longo prazo.
  </li>
</ul>

<h3>Sistemas por Áreas Funcionais</h3>

<p>
  São sistemas especializados em atender as particularidades técnicas de cada
  setor da empresa, como:
</p>

<ul>
  <li>
    <strong>Financeiro e Contábil:</strong> Gestão de caixa e obrigações fiscais.
  </li>
  <li>
    <strong>Processos Industriais e Logística:</strong> Controle de produção e estoque.
  </li>
  <li>
    <strong>Marketing e Recursos Humanos:</strong> Gestão de vendas e de pessoal.
  </li>
</ul>

<p>
  Em resumo, a diferença fundamental entre esses sistemas reside na <strong>
    fonte de coleta
  </strong>
  dos dados e na forma como a informação é
  <strong>tratada e apresentada</strong> para cada perfil de usuário.
</p>

<h3>Infraestrutura de TI e Modelos de Processamento</h3>

<p>
  A infraestrutura deve ser planejada para garantir eficiência e confiabilidade,
  equilibrando o alto custo de investimento com o risco de perda de dados. Os
  computadores são classificados conforme sua capacidade e uso:
</p>

<ul>
  <li>
    <strong>Categorias:</strong> Computador pessoal, estação de trabalho, servidor,
    mainframe, supercomputador e computação em grade.
  </li>
  <li>
    <strong>Modelo Cliente-Servidor:</strong> Divide o processamento entre máquinas
    clientes (interface do usuário) e servidores (armazenamento e processamento pesado),
    conectados em rede.
  </li>
</ul>

<h3>Pilares da Segurança da Informação</h3>

<p>
  A segurança visa proteger a informação contra invasões, roubos e falhas.
  Segundo a literatura técnica, baseia-se em quatro elementos fundamentais:
</p>

<ul>
  <li>
    <strong>Integridade:</strong> Garante que a informação seja fidedigna e não sofra
    alterações não autorizadas (acidentais ou intencionais).
  </li>
  <li>
    <strong>Confidencialidade:</strong> Assegura que o acesso aos dados seja restrito
    exclusivamente a pessoas ou sistemas autorizados.
  </li>
  <li>
    <strong>Autenticidade:</strong> Garante a veracidade da fonte, permitindo identificar
    com precisão a pessoa ou entidade que gerou a informação.
  </li>
  <li>
    <strong>Disponibilidade:</strong> Garante que o sistema e os dados estejam acessíveis
    sempre que solicitados por usuários autorizados, mantendo a continuidade do negócio.
  </li>
</ul>

<h4>Estratégias de Gestão de Riscos</h4>

<p>
  O planejamento de sistemas deve prever mecanismos para lidar com incidentes de
  segurança através de seis ações cíclicas:
</p>

<ol>
  <li><strong>Dissuasão:</strong> Desestimular tentativas de ataque.</li>
  <li>
    <strong>Prevenção:</strong> Implementar barreiras para evitar incidentes.
  </li>
  <li>
    <strong>Detecção:</strong> Identificar rapidamente quando algo errado ocorre.
  </li>
  <li>
    <strong>Contenção:</strong> Isolar o problema para que não se espalhe.
  </li>
  <li>
    <strong>Recuperação:</strong> Retomar as atividades após um incidente.
  </li>
  <li>
    <strong>Restauração:</strong> Colocar o sistema de volta ao seu estado original
    de funcionamento.
  </li>
</ol>

<h4>Conceito de Vulnerabilidade e Ameaças</h4>

<p>
  Vulnerabilidades são fraquezas ou falhas sistêmicas que podem resultar no
  vazamento, alteração ou perda de informações. Elas se manifestam em duas
  esferas principais:
</p>

<ul>
  <li>
    <strong>Âmbito Pessoal:</strong> Decorre do comportamento humano, seja por erros
    acidentais, falta de treinamento ou ações mal-intencionadas para desviar dados.
  </li>
  <li>
    <strong>Âmbito de Infraestrutura:</strong> Relaciona-se a falhas técnicas no
    hardware (como queima de equipamentos) ou no software (presença de programas
    invasores e bugs).
  </li>
</ul>

<p>
  As ameaças surgem quando essas vulnerabilidades são exploradas, comprometendo
  a integridade e a confidencialidade dos ativos da organização.
</p>

<h4>Avaliação e Gestão de Riscos</h4>

<p>
  Para mitigar riscos, é necessário realizar uma avaliação criteriosa que
  fundamente a tomada de decisão. O processo envolve os seguintes passos:
</p>

<ul>
  <li>
    <strong>Mapeamento:</strong> Identificação das informações estratégicas, dos
    bens físicos e das pessoas que manipulam os dados.
  </li>
  <li>
    <strong>Análise de Riscos:</strong> Identificação dos riscos específicos e estimativa
    da probabilidade de sua ocorrência.
  </li>
  <li>
    <strong>Impacto e Consequências:</strong> Definição dos danos caso as ameaças
    se concretizem, incluindo o cálculo de perdas financeiras (pontuais e médias
    anuais).
  </li>
  <li>
    <strong>Planejamento de Medidas:</strong> Pesquisa de alternativas de segurança
    e cálculo do custo de implementação e manutenção das soluções.
  </li>
  <li>
    <strong>Relação Custo-Benefício:</strong> Análise final para garantir que o investimento
    em segurança seja proporcional ao valor dos ativos protegidos.
  </li>
</ul>

<p>
  O objetivo central dessa análise é reduzir prejuízos a longo prazo, evitando
  custos elevados com a inoperabilidade do sistema e outros danos à reputação ou
  ao patrimônio da empresa.
</p>

<h3>A Lógica Sistêmica e o Conhecimento</h3>

<p>
  O desenvolvimento de sistemas baseia-se no fluxo contínuo de dados que, ao
  serem processados, transformam-se em informação e, posteriormente, em
  inteligência (Pirâmide do Conhecimento). Compreender a lógica de entrada,
  processamento, saída e retroalimentação é o ponto de partida essencial para
  qualquer planejamento tecnológico.
</p>

<h4>Integração e Aplicação Organizacional</h4>

<p>
  O planejamento de um sistema deve ser alinhado às necessidades específicas da
  organização, considerando:
</p>

<ul>
  <li>
    <strong>Departamentalização:</strong> As demandas exclusivas de cada setor.
  </li>
  <li>
    <strong>Níveis Hierárquicos:</strong> A distinção entre sistemas operacionais
    (transacionais), táticos (gerenciais) e estratégicos (apoio à decisão).
  </li>
  <li>
    <strong>Integração:</strong> A busca por sistemas que unifiquem dados e facilitem
    a comunicação entre diferentes áreas.
  </li>
</ul>

<h4>Gestão de Riscos e Viabilidade</h4>

<p>
  O encerramento do ciclo de planejamento exige o alinhamento entre as demandas
  de negócio e a segurança. É fundamental identificar vulnerabilidades e aplicar
  medidas que minimizem riscos, sempre pautando-se pela análise de
  custo-benefício. O investimento em segurança e infraestrutura deve ser
  comparado aos prejuízos potenciais de uma eventual perda de dados ou
  inoperabilidade do sistema. Em suma, o desenvolvimento de sistemas de sucesso
  exige uma visão do todo, integrando tecnologia, pessoas e processos
  organizacionais de forma segura e estratégica.
</p>
