<h3>Introdução aos KPIs e BPM</h3>

<p>
  Os Indicadores-Chave de Desempenho (KPIs) servem para avaliar o sucesso e o
  atingimento de metas em qualquer empresa. No contexto do Gerenciamento de
  Processos de Negócios (BPM), as principais etapas são:
</p>

<ol>
  <li>Modelar o processo de negócios usando BPMN.</li>
  <li>Executar o processo modelado em um mecanismo de BPM.</li>
  <li>Medir a execução do processo com KPIs.</li>
  <li>Definir melhorias e otimizar o processo.</li>
</ol>

<h3>Gerenciando Processos</h3>

<p>
  Administrar um processo exige que os gestores aceitem funções
  inter-relacionadas que funcionam de maneira contínua. As funções do
  gerenciamento são: <strong>planejar, organizar, liderar e controlar</strong>.
  Os gerentes definem um plano, organizam os recursos, direcionam os
  funcionários e controlam a eficácia por meio do monitoramento. Para realizar
  uma boa análise de desempenho, é necessário:
</p>

<ul>
  <li>
    Estabelecer indicadores-chave para determinar se o processo ocorre como
    desejado ou se há desvios.
  </li>
  <li>
    Definir indicadores para diferentes períodos de tempo (longo prazo ou em
    tempo real).
  </li>
  <li>
    Definir faixas de valores aceitáveis para cada indicador, sinalizando quando
    ações devem ser tomadas.
  </li>
</ul>

<p>
  A análise de processos fornece informações objetivas que identificam
  oportunidades de melhoria na organização.
</p>

<h3>Características e Escolha dos KPIs</h3>

<p>
  Os KPIs de longo prazo duram de seis meses a um ano e baseiam-se na tecnologia
  de Business Intelligence (BI). O BI permite ao usuário gerar os próprios
  relatórios, navegar pelas informações, recortar, exportar dados e realizar a
  análise final. Escolher o KPI correto é fundamental para tomar decisões
  eficazes baseadas em dados e concentrar esforços em metas significativas,
  evitando o desperdício de recursos com métricas desnecessárias. A definição
  precisa de sucesso exige ir além de uma meta final genérica, detalhando os
  fatores que geram tráfego e receita.
</p>

<h4>Exemplos de KPIs por Área</h4>

<p>
  As empresas constroem seus indicadores conforme suas especificidades. Abaixo
  estão as métricas mencionadas para diferentes setores:
</p>

<ul>
  <li>
    <strong>Finanças:</strong> capital de giro, fluxo de caixa operacional, retorno
    sobre patrimônio, índice rápido, índice de dívida sobre patrimônio, rotação de
    estoque, rotatividade de contas a receber e margem bruta de lucro.
  </li>
  <li>
    <strong>Marketing:</strong> custo de aquisição de clientes, taxa de conversão
    de um canal específico, porcentagem de leads gerados por canal, rotatividade
    de clientes, clientes inativos e gasto médio por cliente.
  </li>
  <li>
    <strong>Assistência médica:</strong> taxa de mortalidade hospitalar, rotatividade
    de leitos, taxa de readmissão, duração média da estadia, satisfação do paciente,
    margem operacional total, custo médio por alta, recebimento em dinheiro para
    dívidas incobráveis e taxa de negação de sinistros.
  </li>
  <li>
    <strong>Varejo:</strong> margem bruta (percentagem do preço de venda), giro de
    estoques, percentual sell-through (métrica mensal de quantidade de produtos vendidos),
    média de vendas por operação e porcentagem de estoque total não exibida.
  </li>
</ul>

<p>
  Para estabelecer KPIs eficazes em uma cultura orientada ao desempenho, é
  necessário definir previamente o resultado desejado pelo negócio, seja cobrar
  um valor do cliente final por um produto/serviço ou alcançar um volume de
  usuários para veiculação de anúncios. No ambiente de inteligência de negócios,
  a medição busca precisão, rapidez e facilidade, iniciando-se pela escolha e
  consenso sobre os KPIs.
</p>

<h3>Tipos de Indicadores</h3>

<p>
  O KPI é uma medida numérica de desempenho para atividades essenciais do
  negócio. Ele não se restringe a dados financeiros, podendo refletir a
  experiência do cliente, o desempenho do produto ou a eficiência operacional.
</p>

<h3>Diferença entre Meta e KPI</h3>

<ul>
  <li>
    <strong>Meta:</strong> Estabelece objetivos de médio e longo prazo, quantificados
    ou qualitativos (estados a atingir, posicionamentos, lideranças).
  </li>
  <li>
    <strong>KPI:</strong> Possui uma métrica que guia ações estratégicas para gerar
    vantagens competitivas e valor para a organização.
  </li>
</ul>

<p>
  Os KPIs podem medir o progresso de metas estratégicas globais (como receita)
  ou focar em objetivos específicos de uma equipe (como satisfação e tempo de
  resposta no suporte, ou custo de aquisição no marketing). O alinhamento entre
  indicadores e métricas menores garante o sucesso da gestão. Compartilhá-los
  unifica o foco da empresa e orienta todos em caso de mudança estratégica.
</p>

<h3>O Caso do Ticket Médio</h3>

<p>
  O ticket médio é um KPI que ajuda a entender a dinâmica de vendas e pode ser
  monitorado por três parâmetros:
</p>

<ul>
  <li><strong>Por venda:</strong> Identifica a performance geral do setor.</li>
  <li>
    <strong>Por cliente:</strong> Revela quem compra mais e melhor, permitindo aperfeiçoar
    o atendimento com vantagens especiais.
  </li>
  <li>
    <strong>Por vendedor:</strong> Identifica os profissionais com melhor desempenho
    para replicar suas práticas e capacitar a equipe.
  </li>
</ul>

<h4>Fórmula do Ticket Médio Mensal:</h4>

<p>Ticket Médio = Faturamento em X meses / X / nº de clientes</p>

<p>
  O acompanhamento dessas métricas permite identificar falhas rapidamente (como
  notar uma queda na taxa de conversão de leads e corrigir um problema de
  usabilidade) e serve como fator de motivação intrínseca para as equipes.
</p>

<h4>Características Únicas dos KPIs</h4>

<p>
  Segundo Sharda, Delen e Turban (2019), os KPIs possuem as seguintes
  características:
</p>

<ul>
  <li><strong>Estratégia:</strong> Encarnam um objetivo estratégico.</li>
  <li>
    <strong>Metas:</strong> Mensuram o desempenho frente a metas de planejamento
    ou orçamento.
  </li>
  <li>
    <strong>Faixas:</strong> Amplitudes de desempenho (pouco acima, no alvo exato
    ou pouco abaixo).
  </li>
  <li>
    <strong>Codificações:</strong> Faixas codificadas em software para exibição visual
    do desempenho.
  </li>
  <li>
    <strong>Prazos:</strong> Delimitam datas-limite para as metas, divididas em intervalos
    menores (marcos).
  </li>
  <li>
    <strong>Benchmarks:</strong> Metas mensuradas com base em um patamar de referência.
  </li>
</ul>

<h4>Classificação e Categorias de KPIs</h4>

<p>Os indicadores se dividem quanto ao seu horizonte e natureza:</p>

<ul>
  <li>
    <strong>KPIs Estratégicos:</strong> Medem o progresso dos objetivos principais;
    não mudam com frequência nem são checados diariamente.
  </li>
  <li>
    <strong>KPIs Operacionais:</strong> Medem a rotina diária que exige atenção urgente;
    mostram o progresso em tempo real e mudam conforme as prioridades.
  </li>
  <li>
    <strong>KPIs Tangíveis:</strong> Elementos concretos e fáceis de observar (ex:
    número de clientes ou volume de vendas).
  </li>
</ul>

<h4>Categorias Principais:</h4>

<ul>
  <li>
    <strong>Indicadores de produtividade:</strong> Produtividade hora/colaborador
    e hora/máquina.
  </li>
  <li>
    <strong>Indicadores de qualidade:</strong> Nível de avarias de um produto e nível
    de aceitação estabelecido.
  </li>
  <li>
    <strong>Indicadores de capacidade:</strong> Capacidade de resposta de um processo
    e quantidade de produtos versus período de tempo.
  </li>
  <li>
    <strong>Indicadores estratégicos:</strong> Cenário atual versus o cenário ideal
    projetado.
  </li>
</ul>

<p>
  Os KPIs não rivalizam com sistemas como OKRs, MBO ou Balanced Scorecard (BSC);
  eles se integram a essas metodologias para representar os objetivos
  estratégicos e medir o desempenho em relação às metas.
</p>

<h4>KPIs para Atingir Metas</h4>

<p>
  Os KPIs são medidas que auxiliam as empresas a acompanhar seu desempenho ao
  longo do tempo e a compreender o significado de sucesso em direção a uma meta.
  As organizações utilizam essas métricas para determinar seu progresso e se
  comparar com os concorrentes. Os indicadores funcionam como ferramentas de
  navegação (como bússolas ou GPS), orientando funcionários, gerentes e empresas
  em suas jornadas estratégicas ou financeiras. Eles ajudam indivíduos de todos
  os níveis a focar no trabalho para atingir os objetivos definidos, permitindo
  que os funcionários entendam o desenvolvimento de suas carreiras e que os
  negócios evoluam com o mercado.
</p>

<h4>Natureza e Setores dos KPIs</h4>

<p>
  Os KPIs variam conforme o setor e os objetivos da organização. Alguns são
  quantitativos e fáceis de mensurar com números concretos (como os ganhos
  financeiros), enquanto outros são mais qualitativos e abertos à interpretação
  (como a satisfação do usuário). Abaixo estão os exemplos listados para
  diferentes setores e contextos:
</p>

<h4>Vendas e Finanças</h4>

<ul>
  <li>Lucro antes de juros, impostos, depreciação e amortização (EBITDA).</li>
  <li>
    Lucro líquido (receita retida após o pagamento de impostos e despesas) e
    lucro bruto (receita após dedução do custo de produção).
  </li>
  <li>Custos (para identificação de reduções).</li>
  <li>
    Comparação entre receita projetada e receita real, e despesas versus
    orçamento.
  </li>
  <li>Relação dívida versus patrimônio.</li>
  <li>
    Vendas por dia pendentes (número médio de dias para receber o pagamento após
    uma venda).
  </li>
  <li>Vendas regionais ou nacionais, e vendas para novos clientes.</li>
  <li>Propostas emitidas e/ou perdidas, e ofertas fechadas.</li>
  <li>Número de reuniões de prospectos em um período definido.</li>
  <li>Número de itens retornados.</li>
  <li>Número de vendas on-line versus vendas na loja.</li>
  <li>
    Rotatividade de estoque (tempo para os produtos em estoque serem vendidos).
  </li>
  <li>Tamanho médio da venda.</li>
  <li>Custo de manutenção da equipe de vendas.</li>
</ul>

<h4>Marketing</h4>

<ul>
  <li>Dinheiro gasto em marketing durante um período.</li>
  <li>
    Tráfego on-line total e tráfego on-line orgânico (visitantes via mecanismos
    de pesquisa).
  </li>
  <li>
    Tráfego da web para determinar novos visitantes versus visitantes que
    retornam.
  </li>
  <li>Tráfego móvel.</li>
  <li>
    Taxa de cliques (proporção do tráfego que clica em um anúncio específico).
  </li>
  <li>
    Número de visitas a um conteúdo específico e crescimento do tráfego nas
    mídias sociais.
  </li>
  <li>Receita de vendas obtidas com campanhas de marketing on-line.</li>
  <li>
    Leads qualificados de marketing (potencial cliente com intenção de compra) e
    leads qualificados de vendas (potencial cliente avaliado e determinado a
    comprar).
  </li>
  <li>Custo por lead.</li>
</ul>

<h4>Relação com o Cliente</h4>

<ul>
  <li>Clientes conquistados por período.</li>
  <li>Tráfego de pedestres na loja.</li>
  <li>
    Porcentagem de clientes que não continuam pagando pelo serviço ou comprando
    produtos.
  </li>
  <li>Custo de aquisição de clientes (CAC).</li>
  <li>
    Valor da vida útil do cliente (para estratégias de obtenção e retenção).
  </li>
  <li>Fidelização e satisfação do cliente (ou pontuação de satisfação).</li>
  <li>Tempo de resposta ou resolução do suporte ao cliente.</li>
  <li>
    Número de chamadas para o atendimento e número de reclamações (por e-mail,
    telefone ou outros métodos).
  </li>
</ul>

<h4>Recursos Humanos e Emprego</h4>

<ul>
  <li>Número de novas contratações e custo por locação.</li>
  <li>Número de promoções.</li>
  <li>Rotatividade de funcionários.</li>
  <li>Satisfação do funcionário medida por pesquisas.</li>
  <li>Taxa de aposentadoria.</li>
  <li>
    Taxa de absentismo (produtividade perdida por motivos pessoais ou de
    doença).
  </li>
  <li>
    Taxa de treinamento e desenvolvimento (com base em resultados pré e
    pós-treinamento).
  </li>
  <li>
    Índice de competitividade salarial (comparação com concorrentes ou setor).
  </li>
</ul>

<h4>Sucesso dos Funcionários</h4>

<ul>
  <li>Metas pessoais (como cotas de venda).</li>
  <li>Conclusão de projetos dentro do prazo.</li>
  <li>Unidades processadas ou problemas resolvidos por período.</li>
  <li>Velocidade de trabalho.</li>
  <li>Satisfação do cliente e satisfação no trabalho.</li>
  <li>Absentismo.</li>
</ul>

<h3>Principais Métricas de Desempenho</h3>

<p>
  Escolher os indicadores de desempenho corretos garante que a empresa meça
  informações relevantes, economizando tempo, dinheiro e recursos. Os
  indicadores escolhidos devem ser sempre mensuráveis, claros e relevantes.
</p>

<h4>Etapas para a Escolha dos KPIs</h4>

<ul>
  <li>
    <strong>Determine um objetivo final:</strong> Crie uma visão clara, simples e
    direta do que a empresa deseja realizar.
  </li>
  <li>
    <strong>Identifique quais dados a empresa já tem:</strong> Verifique se algum
    departamento já coleta as informações necessárias, ajustando a equação para aplicá-la
    à estratégia.
  </li>
  <li>
    <strong>Colete dados de suporte:</strong> Reúna estatísticas sobre tendências
    do setor, dados demográficos e concorrentes. Evite apenas copiar os KPIs da concorrência,
    pois cada empresa é única.
  </li>
  <li>
    <strong>Determine a frequência de medição:</strong> Colete as informações nos
    intervalos apropriados para as necessidades do negócio, garantindo o monitoramento
    útil do KPI.
  </li>
  <li>
    <strong>Defina metas de curto e longo prazo:</strong> Divida os objetivos de
    longo prazo em metas menores para facilitar a avaliação e permitir ajustes na
    estratégia ao longo do processo.
  </li>
  <li>
    <strong>Delegue responsabilidade pelos KPIs:</strong> Determine um funcionário
    ou gerente responsável por avaliar, coletar, interpretar e apresentar os dados
    de cada indicador.
  </li>
  <li>
    <strong>Compartilhe os KPIs com a empresa e partes interessadas:</strong> Mantenha
    a transparência comunicando as estratégias, progressos e resultados para alinhar
    a equipe e obter feedbacks.
  </li>
</ul>

<p>
  Os KPIs não são estáticos e devem ser atualizados conforme as necessidades da
  organização evoluem.
</p>

<h3>Os Princípios SMART e KPQs</h3>

<p>
  Para validar se um indicador de desempenho é útil, a empresa pode aplicar os
  Princípios SMART, respondendo a cinco perguntas:
</p>

<ol>
  <li>
    <strong>Específico (Specific):</strong> A meta que a empresa está segmentando
    é específica?
  </li>
  <li>
    <strong>Mensurável (Measurable):</strong> A empresa é capaz de medir o progresso
    para alcançar esse objetivo?
  </li>
  <li><strong>Atingível (Attainable):</strong> O objetivo é realizável?</li>
  <li>
    <strong>Relevante (Relevant):</strong> O objetivo é relevante para a empresa
    e sua estratégia?
  </li>
  <li>
    <strong>Prazo (Time-bound):</strong> Em que período a empresa espera alcançar
    seu objetivo?
  </li>
</ol>

<h4>Perguntas-Chave de Desempenho (KPQs)</h4>

<p>
  As KPQs são perguntas abertas e instigantes que determinam se a empresa
  atingiu o objetivo (exemplo: "Como a empresa está comercializando seu
  portfólio de produtos?"). As respostas a essas perguntas fornecem o
  embasamento necessário para tomadas de decisão assertivas e para a definição
  de metas produtivas.
</p>

<h3>Modelo Básico para Criar um KPI</h3>

<p>
  O KPI funciona como um indicador de desempenho para tarefas essenciais das
  operações diárias, tendo como uma de suas funções chamar a atenção para áreas
  problemáticas. Os elementos fundamentais que compõem a estrutura de um modelo
  básico de KPI, exemplificados com foco na satisfação do cliente, são os
  seguintes:
</p>

<ul>
  <li>
    <strong>Nome do KPI:</strong> Identificação clara do indicador (Exemplo: Índice
    de satisfação do cliente).
  </li>
  <li>
    <strong>Objetivo:</strong> A estratégia específica que o KPI pretende medir (Exemplo:
    Quão bem estamos aumentando a satisfação do cliente).
  </li>
  <li>
    <strong>Público:</strong> A quem os dados coletados serão apresentados (Exemplo:
    Conselho de administração da empresa).
  </li>
  <li>
    <strong>Acesso:</strong> O departamento ou equipe autorizada a reunir e acessar
    as informações (Exemplo: Departamento de marketing digital).
  </li>
  <li>
    <strong>Questão-Chave de Desempenho (KPQ):</strong> A pergunta exata que o indicador
    responde (Exemplo: "Quão felizes são nossos clientes com nosso serviço?").
  </li>
  <li>
    <strong>Uso do KPI:</strong> A finalidade prática dos dados coletados (Exemplo:
    Avaliar o relacionamento com os clientes).
  </li>
  <li>
    <strong>Fonte de Coleta de Dados:</strong> O método utilizado para obter as informações
    (Exemplo: Pesquisas on-line enviadas por e-mail).
  </li>
  <li>
    <strong>Frequência de Coleta:</strong> O intervalo de tempo necessário para obter
    os novos dados (Exemplo: Mensalmente, com base em amostragem aleatória).
  </li>
  <li>
    <strong>Frequência dos Relatórios:</strong> A periodicidade com que as descobertas
    serão reportadas para manter as informações atuais (Exemplo: Mensalmente).
  </li>
  <li>
    <strong>Responsável:</strong> O cargo ou profissional encarregado de coletar
    e inserir os dados (Exemplo: Assistente de marketing digital).
  </li>
  <li>
    <strong>Avaliação:</strong> Os critérios ou escalas para mensurar o desempenho
    da empresa na área (Exemplo: Escala de 1 a 10, com respostas a partir de 7 consideradas
    positivas).
  </li>
  <li>
    <strong>Metas:</strong> O objetivo quantificável e temporal estabelecido para
    o indicador (Exemplo: Alcançar 75% de aprovação nos próximos dois anos).
  </li>
  <li>
    <strong>Despesa:</strong> O custo financeiro e operacional para coletar e analisar
    os dados (Exemplo: Custo de construção da pesquisa on-line e horas dedicadas
    pelo responsável).
  </li>
  <li>
    <strong>Utilidade e Limitações:</strong> O quanto o KPI responde à KPQ original
    e quais são seus pontos fracos (Exemplo: Gera uma pontuação precisa de satisfação,
    mas traz feedback limitado sobre o que pode ser melhorado).
  </li>
  <li>
    <strong>Consequências Não Intencionais:</strong> Como o comportamento das pessoas
    pode influenciar ou distorcer negativamente os dados (Exemplo: Apenas os clientes
    insatisfeitos optarem por responder à pesquisa).
  </li>
  <li>
    <strong>Data de Vencimento:</strong> O prazo em que o KPI expira ou deve passar
    por revisão (Exemplo: Análise anual para garantir a relevância contínua do indicador).
  </li>
</ul>

<h3>Características para a Efetividade de um KPI</h3>

<p>
  Para que um KPI cumpra seu papel estratégico de forma adequada, ele precisa
  apresentar as seguintes características essenciais:
</p>

<ul>
  <li>Ser efetivo, mensurável e verificável.</li>
  <li>Possuir objetividade e gerar valor agregado.</li>
  <li>Contar com comunicação clara e um objetivo bem definido.</li>
  <li>Ter o comprometimento de todas as pessoas envolvidas.</li>
</ul>

<p>
  A escolha do tipo de KPI a ser criado (seja de capacidade, produtividade,
  qualidade, lucratividade, rentabilidade, competitividade, efetividade ou
  valor) deve priorizar os fatores mais importantes para a definição e
  sustentação das estratégias da empresa.
</p>

<h3>Conclusão</h3>

<ul>
  <li>
    <strong>Funções de Gerenciamento:</strong> Administrar um processo exige que
    todos os gestores utilizem suas habilidades em quatro funções inter-relacionadas
    e contínuas para alcançar os objetivos da empresa: planejar, organizar, liderar
    e controlar.
  </li>
  <li>
    <strong>Categorias de KPIs:</strong> Após a definição dos indicadores, o acompanhamento
    do processo é feito por métricas essenciais. As categorias dividem-se em indicadores
    de produtividade, qualidade, capacidade e estratégicos.
  </li>
  <li>
    <strong>Segmentação por Setor:</strong> As medidas de desempenho variam conforme
    os objetivos da organização e o setor de atuação, aplicando-se principalmente
    a: vendas e finanças; marketing; relação com o cliente; recursos humanos e emprego;
    e sucesso dos funcionários.
  </li>
  <li>
    <strong>Eficiência na Escolha:</strong> Selecionar os indicadores de desempenho
    corretos garante que a empresa foque em informações relevantes, o que gera economia
    de tempo, dinheiro e recursos operacionais.
  </li>
  <li>
    <strong>O Modelo Básico do KPI:</strong> O indicador aponta o desempenho de tarefas
    essenciais da rotina. Sua criação estruturada deve contemplar: nome, objetivo,
    público, acesso, questão-chave, uso, fonte de coleta de dados, frequência de
    coleta, relatórios, responsável, avaliação, metas, despesa, utilidade, limitação
    e vencimento.
  </li>
</ul>
