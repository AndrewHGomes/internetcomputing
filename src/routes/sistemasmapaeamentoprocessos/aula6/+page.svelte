<h2>Mapeamento do Conhecimento</h2>

<Audios modulo="M13" aulas={["21", "22", "23", "24"]} />

<p>
  O mapeamento do conhecimento é uma abordagem avançada de gestão que gera uma
  representação visual do capital intelectual de uma organização. Ele permite
  que os stakeholders identifiquem a localização do conhecimento crítico, seu
  fluxo, além de barreiras ou lacunas nos processos. Essa ferramenta mantém as
  informações principais de um tópico centralizadas em um único local,
  facilitando o acesso, a navegação e a compreensão por qualquer pessoa da
  equipe.
</p>

<h4>Utilidade do Mapeamento do Conhecimento</h4>

<ul>
  <li>Criar auxílios visuais;</li>
  <li>Economizar tempo e melhorar a eficiência do fluxo de trabalho;</li>
  <li>Permitir uma melhor colaboração entre as equipes;</li>
  <li>
    Gerenciar projetos e eventos, desenvolver produtos e realizar planejamento
    estratégico.
  </li>
</ul>

<h4>Aplicação e Implementação</h4>

<p>
  O processo envolve documentar as habilidades e os conhecimentos únicos dos
  indivíduos, bem como suas alterações ao longo do desenvolvimento. A aplicação
  prática segue a lógica de:
</p>

<ol>
  <li>Identificar o indivíduo certo para uma tarefa específica.</li>
  <li>Prever e mitigar possíveis riscos.</li>
  <li>
    Facilitar o intercâmbio de ideias e informações para solucionar problemas.
  </li>
</ol>

<p>
  Muitas organizações utilizam mapas baseados em processos para documentar
  conteúdo, contatos e know-how desde a integração de novos funcionários ou
  clientes, podendo funcionar como um documento-mestre de fluxos de trabalho
  associado a links de bibliotecas virtuais.
</p>

<h3>Estrutura do Mapa de Conhecimento</h3>

<p>
  Mais do que uma representação gráfica, o mapa captura e compartilha ideias,
  experiências, interpretações e previsões. Ele organiza módulos interconectados
  (nós) que se vinculam diretamente às informações principais. Cada nó ou módulo
  corresponde a elementos como:
</p>

<ul>
  <li>Documentos, modelos e tabelas;</li>
  <li>Diagramas e infográficos;</li>
  <li>Mapas mentais, fluxogramas ou mapas conceituais;</li>
  <li>Imagens, esboços e animações;</li>
  <li>Informações de contato para pessoal interno e externo.</li>
</ul>

<p>
  O resultado é uma ferramenta visual dinâmica que pode ser atualizada e
  expandida conforme a necessidade da empresa.
</p>

<h3>Etapas do Mapeamento do Conhecimento</h3>

<p>
  As etapas do mapeamento transformam o conhecimento (ativo intangível) em
  benefícios tangíveis, como melhoria de desempenho e produtividade, além de
  ajudarem a identificar lacunas operacionais. O processo tem como
  elemento-chave a construção de uma memória institucional através da
  identificação dos ativos de conhecimento. Isso garante a organização e a
  padronização dos processos para atender aos objetivos do negócio.
</p>

<h4>Escolha o tópico do seu mapa</h4>

<p>
  A primeira etapa consiste em reunir a equipe e definir o tópico central do
  mapa que será criado. Diretrizes para esta etapa:
</p>

<ul>
  <li>
    Utilizar softwares que disponibilizem modelos prontos para estruturar os
    estágios do mapeamento.
  </li>
  <li>
    Escolher uma personalização que reflita com clareza os objetivos
    pretendidos.
  </li>
  <li>
    Organizar e separar os mapas de forma estruturada pelos tópicos de
    conhecimento criados (nós ou módulos).
  </li>
</ul>

<h3>Benefícios e Ferramentas do Mapeamento</h3>

<p>
  O mapeamento de conhecimento gera experiência para os envolvidos e faz surgir
  a inteligência coletiva. O uso de softwares específicos torna o processo
  intuitivo, organizando o capital intelectual em ativos de conhecimento que
  podem ser acessados rapidamente. Como as pessoas possuem diferentes processos
  de pensamento, a equipe pode navegar pelas ramificações do mapa por caminhos
  variados para alcançar grupos de ativos e novos mapas.
</p>

<h4>Criar ou coletar os principais recursos do conhecimento</h4>

<p>
  Esta etapa consiste em redigir o mapa com base nas representações locais ou
  pessoas que detêm informações importantes, filtrando dados irrelevantes que
  não agregam valor. O processo inicia-se com a identificação dos principais
  elementos (nós ou módulos). No exemplo de planejamento de uma conferência, os
  elementos incluem:
</p>

<ul>
  <li>Escolha do tema e determinação do orçamento;</li>
  <li>Escolha do local e definição de palestrantes (alto-falantes);</li>
  <li>Solicitação de patrocinadores e determinação de voluntários;</li>
  <li>
    Definição do responsável por detalhar o mapa (organizadores anteriores ou
    pessoas experientes);
  </li>
  <li>
    Anexação de recursos relevantes (listas de ideias, divisão de tarefas,
    custos, contatos de centros de conferências, especialistas, etc.).
  </li>
</ul>

<p>
  A partir desses pontos, o mapa deve continuar ramificando-se para recursos
  mais específicos conforme a necessidade (ex: modelos de e-mail para
  patrocinadores ou voluntários vinculados aos seus respectivos nós).
</p>

<p>
  <strong>Mapeamento de Competências:</strong> Identifica e mapeia as competências
  organizacionais que a empresa precisa desenvolver para alcançar seus objetivos.
</p>

<h4>Crie uma pasta para seu mapa do conhecimento</h4>

<p>
  Consiste em criar uma pasta centralizada para armazenar todos os documentos,
  modelos e recursos visuais associados ao mapa. Essa pasta permite o
  compartilhamento das atividades com a equipe, possibilitando edições,
  atualizações e sugestões em tempo real. Com o mapa em andamento ou finalizado,
  inserem-se links que levam o usuário diretamente do nó específico ao recurso
  de informação correspondente na pasta. O objetivo final das etapas de
  mapeamento é criar uma ferramenta clara, completa e acionável, permitindo que
  qualquer pessoa na organização seja guiada do início ao fim do processo.
</p>

<h3>O Papel do Conhecimento nos Negócios</h3>

<p>
  O conhecimento é o fator mais crítico para o crescimento dos negócios e para a
  satisfação do cliente, funcionando como uma vantagem competitiva. Empresas que
  negligenciam o conhecimento corporativo perdem oportunidades de gerenciar o
  relacionamento com clientes, aumentar a receita e competir no mercado. A
  eficácia da estratégia de gestão depende de três elementos-chave (pilares do
  conhecimento corporativo), que devem ser mantidos estáveis a partir de uma
  base sólida fomentada pelo mapeamento.
</p>

<h4>Conecte mapas do conhecimento conforme eles são criados</h4>

<p>
  Após a conclusão de um mapa, ele deve ser conectado a todas as áreas de
  conhecimento correlatas da empresa. Os recursos criados devem ser
  continuamente adicionados a pastas novas ou existentes, pois documentos,
  planilhas e contatos frequentemente aplicam-se a mais de um tópico. No exemplo
  de Planejamento de Conferência, os recursos podem agregar valor e ser
  integrados a outros mapas, tais como:
</p>

<ul>
  <li>Planejamento de eventos;</li>
  <li>Orçamento de custos;</li>
  <li>Projetos orientados a patrocinadores.</li>
</ul>

<p>
  Deve-se explorar o potencial de sobreposição de recursos entre diferentes
  departamentos. Informações enviadas a palestrantes ou patrocinadores, por
  exemplo, podem ser compartilhadas com mapas das equipes de marketing ou
  finanças. O objetivo é otimizar o fluxo de informações, criando um auxílio
  visual que economize tempo e direcione os usuários exatamente ao que precisam.
</p>

<p>
  <strong>Vertentes do Mapeamento (Possi, 2006):</strong> O mapeamento do conhecimento
  pode ser tratado nas vertentes intelectual, de relacionamento e estrutural, considerando
  os seguintes dados:
</p>

<ul>
  <li>
    <strong>Entradas:</strong> Mapa de expertise da organização, equipe do projeto
    e declaração de conhecimentos estratégicos.
  </li>
  <li>
    <strong>Ferramentas e técnicas:</strong> Análise do mapa da organização, modelo
    de mensuração e avaliação do nível de conhecimento, e ferramentas de mensuração
    e avaliação.
  </li>
  <li><strong>Saídas:</strong> Mapa de expertise.</li>
</ul>

<p>
  Em suma, as empresas devem visualizar seus processos de forma abrangente e
  transparente, levantando, avaliando e vinculando informações, conhecimentos,
  competências e habilidades de seu ambiente.
</p>

<h3>Técnicas de Mapeamento do Conhecimento</h3>

<p>
  Existem diferentes técnicas para mapear o conhecimento organizacional. Cada
  uma utiliza um conjunto específico de ferramentas, abordagens, objetivos e
  características para atender às necessidades e expectativas da organização.
</p>

<h4>Páginas Amarelas</h4>

<p>
  Consistem em uma coleção estruturada de dados e documentos sobre as pessoas da
  empresa para facilitar a comunicação e o compartilhamento de conhecimentos e
  habilidades entre indivíduos e grupos. Geralmente funcionam por meio de
  aplicativos internos de comunicação.
</p>

<ul>
  <li>
    <strong>Desvantagens:</strong> Podem apresentar problemas na análise da qualidade,
    no conhecimento real das pessoas e na atualização das informações.
  </li>
</ul>

<h4>Análise de Fluxo de Informações</h4>

<p>
  Determina quem acessa quais recursos de informação e com que frequência. Pode
  ser executada por programas de computador complexos ou por métodos básicos,
  tais como:
</p>

<ul>
  <li>Captura de dados de uso em tempo real via log out nos sistemas;</li>
  <li>
    Aplicação de questionários ou entrevistas focadas em descobrir onde as
    pessoas pesquisam, quais recursos mais utilizam e para onde enviam as
    informações.
  </li>
</ul>

<h4>Análise de Redes Sociais</h4>

<p>
  Mapeia e mede os relacionamentos ou fluxos de informação e conhecimento entre
  pessoas, grupos, organizações e computadores interligados em rede. Utiliza
  sistemas complexos para fornecer análises visuais e matemáticas, buscando
  entender como o conhecimento tácito (as percepções de quem conhece) é
  transmitido e como pode ser aprimorado.
</p>

<h4>Mapeamento do Conhecimento do Processo</h4>

<p>
  Define o conhecimento necessário e o disponível para apoiar um processo de
  negócios. Ele identifica:
</p>

<ul>
  <li><strong>Pontos de decisão:</strong> Onde o conhecimento é necessário;</li>
  <li>
    <strong>Requisitos de conhecimento:</strong> Qual conhecimento é necessário;
  </li>
  <li>
    <strong>Acesso e recuperação:</strong> As pessoas e tecnologias envolvidas;
  </li>
  <li>
    <strong>Habilidades necessárias:</strong> Posição de quem cumpre a etapa, treinamentos
    requeridos, experiências, recursos e procedimentos.
  </li>
</ul>

<h4>Mapeamento do Conhecimento Funcional</h4>

<p>
  Processo passo a passo detalhado (semelhante ao de processo) que lista o
  conhecimento e os contatos sociais do indivíduo relacionados à sua posição
  atual. Ele determina quais indivíduos possuem habilidades, experiências,
  formação acadêmica e outros recursos que podem ser aplicados em outras áreas,
  criando um diretório organizacional de propriedades individuais.
</p>

