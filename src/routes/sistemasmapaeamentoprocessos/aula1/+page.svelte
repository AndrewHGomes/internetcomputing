<h3>Visão Sistêmica na Gestão Integrada</h3>

<p>
  Ter uma visão de sistemas significa observar as interações entre nós, os
  ambientes em que vivemos e os sistemas que nos cercam e dos quais fazemos
  parte. Essa abordagem gera benefícios no local de trabalho e permite analisar
  problemas de negócios sob novas perspetivas.
</p>

<h4>Tipos de Pensamento</h4>

<p>
  O pensamento é uma atividade mental organizada e racional que correlaciona e
  integra atividades no tempo e no espaço. Ele estimula ideias ou memórias,
  ativando redes cerebrais para obter informações necessárias para determinados
  eventos.
</p>

<h4>O Pensamento Sistêmico</h4>

<p>
  É uma ferramenta de diagnóstico e uma abordagem disciplinada para examinar
  problemas de forma completa e precisa antes de tomar ações. Permite fazer
  perguntas eficazes e evita conclusões precipitadas. O processo envolve passar
  da observação de eventos e dados para a identificação de padrões, buscando
  entender e modificar estruturas e modelos mentais que não funcionam bem.
  Requer curiosidade, clareza, compaixão, escolha e coragem, além da disposição
  para ver situações de forma completa e reconhecer a interrelação e as
  múltiplas intervenções possíveis. Resultados esperados do pensamento sistêmico
  na organização:
</p>

<ul>
  <li>
    <strong>Otimização:</strong> Permite o aproveitamento máximo de qualquer elemento
    do sistema.
  </li>
  <li>
    <strong>Inovação:</strong> Transforma a complexidade e os problemas em oportunidades
    de desenvolvimento criativo.
  </li>
  <li>
    <strong>Visão holística:</strong> Examina o ecossistema ou organismo como um
    todo, e não as partes individuais.
  </li>
  <li>
    <strong>Circularização:</strong> Permite projetar produtos e serviços de forma
    circular, eliminando desperdícios e ineficiências dos sistemas lineares humanos.
  </li>
  <li>
    <strong>Aprendizado com o fracasso:</strong> Elimina a culpa e utiliza falhas
    para obter novas perspetivas e capacidade criativa, já que tudo está interconectado.
  </li>
  <li>
    <strong>Integração na rotina:</strong> Fornece ferramentas para integrar a interconectividade,
    base da criatividade e da produtividade, nas práticas diárias.
  </li>
  <li>
    <strong>Desenvolvimento cerebral:</strong> Estimula a criatividade à medida que
    se desenvolve uma compreensão dinâmica do mundo.
  </li>
</ul>

<h4>O Pensamento Enxuto (Lean)</h4>

<p>
  Descreve o processo de tomada de decisões de negócios de maneira enxuta,
  servindo como o fundamento de qualquer prática Lean. Originou-se no chão de
  fábrica da Toyota com o Sistema de Produção Toyota (TPS), que serve de base
  para as práticas modernas de fabricação enxuta. Diretrizes e princípios do
  pensamento enxuto:
</p>

<ul>
  <li>
    <strong>Consciência do desperdício:</strong> O desperdício está na perceção das
    pessoas que realizam o trabalho, englobando sistemas de informação ineficientes,
    ferramentas precárias e má comunicação.
  </li>
  <li>
    <strong>Criação de conhecimento:</strong> Incorpora o aprendizado e o ensino
    nas organizações para que mais pessoas agreguem valor, exigindo a criação de
    ambientes que deem espaço ao aprendizado.
  </li>
  <li>
    <strong>Crescimento e qualidade:</strong> Protege o sistema através da padronização
    e automatização de tarefas tediosas, repetitivas ou propensas a erros, concentrando
    os esforços humanos na inovação e melhoria contínua.
  </li>
  <li>
    <strong>Entrega rápida e gestão do fluxo:</strong> Incentiva a visualização,
    gestão e otimização contínua do fluxo de processos para agregar valor ao cliente
    em ritmo sustentável e rápido, exigindo controlo sobre a execução do trabalho.
  </li>
  <li>
    <strong>Adiar o compromisso (flexibilidade):</strong> Incentiva a tomada de decisões
    no último momento útil, com base em informações atualizadas e abrangentes. Evita
    planear ou concluir o trabalho antes do necessário, prevenindo o gasto de tempo
    e dinheiro em produtos indesejados pelo mercado.
  </li>
  <li>
    <strong>Respeito pelas pessoas:</strong> Reconhece que o valor da organização
    está na mente dos colaboradores. O respeito manifesta-se ao fornecer o necessário
    para o trabalho, criar ambientes onde as melhores ideias são ouvidas, incentivar
    a educação e dar autonomia para decidir o que é melhor para o cliente.
  </li>
</ul>

<h3>Mapeamento de Processos</h3>

<p>
  O mapeamento de processo consiste em descrever as atividades em termos de como
  elas se relacionam entre si. Um mapa de processo funciona como uma
  representação visual que expressa as informações de maneira clara e concisa,
  substituindo longos textos descritivos. Independentemente da técnica utilizada
  (como blueprinting ou análise de processo), o mapeamento identifica os
  diferentes tipos de atividades e demonstra o fluxo de materiais, pessoas ou
  informações que percorrem o processo.
</p>

<h4>Objetivos e Benefícios do Mapa de Processo</h4>

<p>
  O objetivo final do mapeamento é melhorar a eficiência, identificar gargalos
  ou problemas em potencial e definir responsabilidades, tornando as informações
  fáceis de entender por todos. Os mapas de processo são utilizados para:
</p>

<ul>
  <li>
    Ajudar na compreensão de fluxos de trabalho complexos por meio da
    comunicação visual.
  </li>
  <li>Mostrar um processo inteiro do início ao fim.</li>
  <li>Otimizar e melhorar processos específicos.</li>
  <li>
    Melhorar a comunicação entre as partes interessadas envolvidas ou que buscam
    entender o processo.
  </li>
  <li>Fornecer documentação técnica.</li>
  <li>Auxiliar no planejamento e na tomada de decisão.</li>
  <li>Ajudar em testes de cenário e avaliações hipotéticas.</li>
  <li>
    Provar a investidores ou partes interessadas que os processos de negócios
    são confiáveis.
  </li>
  <li>Treinar novos funcionários.</li>
  <li>
    Atuar como ponto de partida para diagramas mais complexos (diagramas de
    fluxo de dados, fluxogramas, entre outros).
  </li>
  <li>Cumprir padrões e certificações, como a ISO 9000.</li>
</ul>

<h4>Aplicações Integradas</h4>

<p>
  O mapeamento de processos também permite uma melhor visualização das
  atividades quando utilizado em conjunto com metodologias de melhoria de
  qualidade e de negócios, tais como:
</p>

<ul>
  <li>Lean</li>
  <li>Seis Sigma</li>
  <li>Melhoria do Processo de Negócios</li>
  <li>Melhoria Contínua ou Kaizen</li>
  <li>Reengenharia do processo de negócios</li>
  <li>Business Analyst</li>
</ul>

<h3>Símbolos do Mapeamento do Processo</h3>

<p>
  O mapeamento de processo é uma ferramenta que exibe as etapas das atividades,
  entradas, saídas e detalhes relacionados, fornecendo uma imagem do estado
  atual e do passo a passo do processo. Os símbolos do mapeamento são utilizados
  para classificar os diferentes tipos de atividades que ocorrem ao longo do
  fluxo.
</p>

<h4>O Fluxograma</h4>

<p>
  O fluxograma (ou fluxograma do processo) é uma técnica e ferramenta gráfica
  que descreve etapas distintas de um processo em ordem sequencial, apresentando
  um início e um fim. Suas principais características e objetivos são:
</p>

<ul>
  <li>
    Integrar o conhecimento ao combinar todas as pessoas associadas a um
    processo.
  </li>
  <li>
    Utilizar símbolos determinados para identificar etapas e facilitar a
    compreensão do fluxo atual.
  </li>
  <li>
    Incluir todas as etapas de importância crítica para o processo e suas
    respectivas informações de desempenho.
  </li>
</ul>

<h4>Exemplo de Aplicação</h4>

<p>
  A disposição desses símbolos serve para descrever qualquer tipo de processo.
  Como exemplo prático, a técnica pode ser aplicada para mapear operações de
  suprimento e instalação, como a atividade de verificação de segurança
  realizada nas instalações de um cliente para garantir a conformidade com as
  regulamentações vigentes.
</p>

<h3>Visibilidade do Processo</h3>

<p>
  O mapeamento completo de um negócio exige estabelecer total visibilidade e
  controle sobre os processos. Mapear as etapas tornando óbvio o grau de
  visibilidade de cada parte permite que os trechos com alta visibilidade sejam
  projetados especificamente para melhorar a percepção do cliente sobre o
  processo. Muitas empresas utilizam softwares visuais de mapeamento de
  processos para obter um gerenciamento mais simplificado, o qual incentiva a
  colaboração em toda a organização, aumenta a responsabilidade e busca a
  melhoria contínua.
</p>

<h4>Avanço e Automação de Processos</h4>

<p>
  Para alcançar um mapeamento eficaz e integrar a automação, as empresas
  precisam capacitar os especialistas responsáveis por essa automação, tornando
  os processos livres de barreiras técnicas. As etapas para atingir esse
  gerenciamento simplificado envolvem:
</p>

<ul>
  <li>Avaliar e melhorar os processos utilizando ferramentas simples.</li>
  <li>Estabelecer a propriedade dos processos.</li>
  <li>Encontrar ineficiências ou pontos fracos nos processos da empresa.</li>
  <li>
    Eliminar a probabilidade de a organização gastar tempo em processos
    interrompidos.
  </li>
</ul>

<h4>Papel dos Mapas de Processos</h4>

<p>
  Os mapas de processos atuam como um método para tornar os fluxos visíveis.
  Eles permitem que as partes interessadas formem um entendimento único e
  compartilhado sobre a operação da empresa, servindo como um ponto de
  referência concreto para a tomada de decisões.
</p>

<h3>Tipos de Mapas de Processo</h3>

<p>
  Não existe um modelo único de mapeamento. É necessário alternar entre os tipos
  existentes para adequá-los às metas específicas de cada projeto.
</p>

<ul>
  <li>
    <strong>Mapa do processo de atividades:</strong> Representa as atividades que
    agregam valor e identifica as que não agregam valor. É útil para otimizar o fluxo
    de trabalho e gerenciar orçamentos, pois evidencia as ações que afetam diretamente
    a receita.
  </li>
  <li>
    <strong>Mapa detalhado do processo:</strong> Fornece uma visão minuciosa de cada
    etapa do processo atual, permitindo conhecer e compreender o fluxo como um todo.
  </li>
  <li>
    <strong>Mapa da raia (ou interfuncional):</strong> Separa dois ou mais fluxos
    dentro da organização, mas mantém a sua interconexão. As raias são usadas para
    representar áreas funcionais, clientes e fornecedores.
  </li>
  <li>
    <strong>Mapa do processo em avaliação:</strong> Representa o estado atual e/ou
    o estado futuro dos processos com o objetivo de localizar áreas para melhoria.
  </li>
  <li>
    <strong>Mapa SIPOC:</strong> É uma forma de diagrama de raia com uma representação
    de alto nível. Envolve de forma detalhada e sequencial as interações entre Fornecedor,
    Entrada, Processo, Saída e Cliente (Suppliers, Inputs, Process, Outputs, Customers).
    Foca na análise dos aspectos do fluxo de trabalho e na distinção de seus níveis
    de importância.
  </li>
  <li>
    <strong>Mapa do fluxo de valor:</strong> Técnica de gerenciamento enxuto (Lean)
    que analisa o estado atual dos processos e projeta um estado futuro aprimorado,
    cobrindo o fluxo desde o início até o produto ou cliente final. Cada etapa é
    representada por uma caixa no topo do mapa, indicando os fatos reais que ocorreram
    com o recurso.
  </li>
  <li>
    <strong>Diagrama do fluxo de trabalho:</strong> Fornece uma visualização de alto
    nível do processo de negócio como um todo. Pode ser utilizado por meio de diagramas
    de atividades para especificar outros processos, como na modelagem de sistemas.
  </li>
</ul>

<h3>Conclusão</h3>

<ul>
  <li>
    <strong>Tipos de pensamento:</strong> São utilizados para a elaboração de estratégias
    e ações focadas em gerar benefícios tanto no âmbito pessoal quanto no profissional.
  </li>
  <li>
    <strong>Mapeamento de processos:</strong> É uma ferramenta de gestão usada para
    identificar informações, fluxos de trabalho, recursos e todos os envolvidos nas
    atividades.
  </li>
  <li>
    <strong>Símbolos do mapeamento (Fluxograma):</strong> Representam graficamente
    a sequência de todas as etapas de uma atividade, utilizando comumente ícones
    arredondados, retângulos, losangos e setas.
  </li>
  <li>
    <strong>Visibilidade do processo:</strong> Permite enxergar lacunas, desvios
    e gargalos, viabilizando a otimização, a documentação e a comunicação do processo.
  </li>
  <li>
    <strong>Tipos de mapas de processo:</strong> Atendem às empresas com estratégias
    específicas e auxiliam na implementação do mapeamento, funcionando como métodos
    e ferramentas que estruturam o processo para facilitar sua análise.
  </li>
</ul>
