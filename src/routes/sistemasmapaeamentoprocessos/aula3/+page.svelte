<h3>Introdução à Análise de Negócios</h3>

<p>
  A análise de negócios identifica as necessidades de uma empresa e define
  soluções para os problemas que surgem. A inclusão de softwares como
  componentes no sistema de desenvolvimento da análise é fundamental. Eles
  oferecem conceitos e ideias para estruturar a base inicial de qualquer
  projeto, orientando as partes interessadas na modelagem dos negócios de
  maneira ordenada.
</p>

<h3>Processos de Negócio</h3>

<p>
  Os processos são o núcleo de uma empresa, existem em todos os departamentos e
  equipes, e são pontos críticos para o sucesso das operações. Fazer com que o
  trabalho funcione sem problemas exige tempo, recursos e planejamento. O ponto
  de partida para isso é o gerenciamento de processos de negócio.
</p>

<h3>Gerenciamento de Processos de Negócio (BPM)</h3>

<p>
  O Business Process Management (BPM) é a prática de projetar, executar,
  monitorar e otimizar processos de negócio. Trata-se de uma metodologia focada
  na melhoria contínua e na transformação da empresa em uma estrutura eficiente.
  O objetivo do BPM é maximizar o valor adicionado por um processo, o que é
  avaliado por meio de medidas de desempenho. A prática deve focar na geração de
  resultados (como ganho de eficiência) e considerar o processo completo, de
  ponta a ponta, não devendo ser confundida com a simples automação do fluxo de
  trabalho.
</p>

<h4>Características e Automação dos Processos</h4>

<ul>
  <li>
    <strong>Processos estruturados:</strong> Possuem um caminho previsível do início
    ao fim, são repetíveis e são bons candidatos à automação.
  </li>
  <li>
    <strong>Processos desestruturados:</strong> Apresentam um caminho menos previsível
    para atingir uma meta.
  </li>
</ul>

<p>
  A automação é realizada por softwares de BPM, que suportam o desenvolvimento
  de aplicativos e soluções tecnológicas para os processos.
</p>

<h3>Objetivos e Benefícios do BPM</h3>

<p>
  A gestão por BPM busca conduzir os negócios da maneira mais eficiente
  possível. Sua aplicação orientada a resultados pode ser feita em qualquer
  fluxo de trabalho ou função, trazendo as seguintes ações e benefícios:
</p>

<ul>
  <li>Otimização da alocação de recursos.</li>
  <li>Eliminação de gargalos.</li>
  <li>Redução da duplicação de processos.</li>
  <li>Aceleração de transações.</li>
  <li>Melhoria das operações e dos resultados gerais.</li>
  <li>Fortalecimento da empresa contra os riscos de mercado.</li>
</ul>

<h3>Mapeamento do Processo To Be ("Como Deve Ser")</h3>

<p>
  O processo to be representa a situação futura esperada, focando em melhorias
  de ruptura ou no atendimento de demandas de mercado, normativas ou estratégias
  da empresa. Essa fase ocorre após a revisão do processo atual (as is) e visa
  criar fluxos mais eficientes e eficazes.
</p>

<h3>O Processo Atual (As Is)</h3>

<p>
  O objetivo de mapear o processo as is é conhecer a operação detalhadamente,
  sem antecipar soluções. As ferramentas utilizadas para esse levantamento são:
</p>

<ul>
  <li>Reuniões, entrevistas isoladas ou em grupo.</li>
  <li>Workshops de levantamento e questionários.</li>
  <li>Observações em campo e coleta de documentos/evidências.</li>
  <li>Análise de sistemas legados.</li>
  <li>
    Definição da notação, padrão de documentação e ferramentas de modelagem.
  </li>
  <li>Validação e apresentação do modelo.</li>
</ul>

<h3>Atividades do Design do Processo To Be</h3>

<p>
  Na fase to be, os cenários de simulação são cruciais para comparar o processo
  atual com o futuro. O desenho dos novos processos exige o desenvolvimento de
  seis atividades principais:
</p>

<h4>Projeto de Processo (To Be)</h4>

<p>
  Oferece à empresa o que se espera realizar, devendo ser documentado por
  escrito com atividades detalhadas, regras de negócio e interações com clientes
  e produtos. Utiliza metodologias como estudo de cenários, brainstorming,
  modelagem em tempo real e quadros de anotações para definir como os objetivos
  serão alcançados.
</p>

<h4>Definição de Atividades do Processo</h4>

<p>
  As atividades devem ser simples, objetivas e de fácil compreensão. Devem ser
  ordenadas e descritas pelo que será feito, sem apego aos agentes do processo,
  criando paralelos entre elas.
</p>

<h4>Análise de Lacunas e Comparações</h4>

<p>
  O processo to be deve ser superior ao as is. Ferramentas de simulação comparam
  os resultados atuais com os objetivos pretendidos para:
</p>

<ul>
  <li>Descrever as alterações do novo processo.</li>
  <li>Obter ganhos tangíveis e documentar resultados esperados.</li>
  <li>Aumentar a colaboração e o suporte ao novo modelo.</li>
</ul>

<h4>Projetar e Analisar a Infraestrutura de TI</h4>

<p>
  Analisa o fluxo de dados, formulários, sistemas, interfaces, além de quem
  usará a informação e quando ela será usada. O intuito é definir a
  infraestrutura de TI sem comprometer o desempenho ou desperdiçar recursos.
</p>

<h4>Modelo de Simulação, Teste e Aceitação</h4>

<p>
  Utiliza a tecnologia para prever resultados com agilidade e confiança. É o
  momento de definir limites, prever falhas, corrigi-las e estimar os riscos
  cuidadosamente antes da certificação.
</p>

<h4>Criação do Plano de Implantação</h4>

<p>
  Define o gerenciamento de mudanças, identificando os sistemas afetados e as
  equipes envolvidas. Falhas ou desorganização nesta etapa comprometem todo o
  trabalho anterior.
</p>

<h3>Ferramentas de Suporte ao BPM</h3>

<p>
  Uma boa ferramenta de mapeamento de BPM auxilia tanto no projeto quanto na
  implementação. Recursos que permitem criar fluxos de informação, gráficos de
  controle e alertas trazem transparência e viabilizam a visualização
  instantânea dos indicadores de desempenho.
</p>

<h3>Análise de Negócios</h3>

<p>
  A análise de negócios consiste em um conjunto de tarefas e técnicas utilizadas
  para interligar as partes interessadas (stakeholders), permitindo compreender
  a estrutura, as políticas e as operações de uma organização. O processo foca
  na mudança estrutural, estratégica, política, processual ou de sistemas de
  informação para que a empresa atinja seus objetivos. O analista de negócios
  deve analisar e sintetizar informações fornecidas por diversos atores, como
  clientes, colaboradores, profissionais de TI e executivos, entendendo como a
  empresa funciona e define seus recursos para entregar valor.
</p>

<h3>Ferramentas de Análise de Negócios</h3>

<p>
  As ferramentas moldam a seleção de técnicas e notações, além de melhorarem a
  produtividade e a gestão empresarial. Softwares comuns atuam no armazenamento
  e distribuição de informações, divididos nas seguintes categorias:
</p>

<ul>
  <li>
    <strong>Processadores de texto:</strong> Desenvolvimento e manutenção de documentos
    de requisitos.
  </li>
  <li>
    <strong>Planilhas:</strong> Manutenção de listas, dados numéricos, análise decisória
    e rastreamento de mudanças.
  </li>
  <li>
    <strong>Softwares de apresentação:</strong> Treinamento e discussões entre stakeholders.
  </li>
  <li>
    <strong>Gestão e gestão do conhecimento:</strong> Captura de conhecimento distribuído,
    disponibilização de documentos e fóruns.
  </li>
  <li>
    <strong>Ferramentas de comunicação:</strong> E-mail e aplicativos de mensagens
    em tempo real.
  </li>
  <li>
    <strong>Modelagens de negócio:</strong> Validação e implementação de modelos.
  </li>
  <li>
    <strong>Ferramentas de diagramação:</strong> Desenho e uso de templates.
  </li>
</ul>

<h3>Critérios de Eficácia no Uso de Aplicativos</h3>

<ul>
  <li>Aplicar o conhecimento de uma ferramenta em outras similares.</li>
  <li>
    Identificar as melhores ferramentas do mercado e descrever sua utilidade.
  </li>
  <li>
    Compreender e utilizar a maior parte das funcionalidades da ferramenta.
  </li>
  <li>Completar atividades de forma mais rápida do que sem o uso delas.</li>
  <li>Rastrear as mudanças realizadas por meio das ferramentas.</li>
</ul>

<h3>Conceito de Requisito</h3>

<p>O requisito pode ser definido sob três perspectivas complementares:</p>

<ol>
  <li>
    Uma condição ou capacidade necessária a um stakeholder para solucionar um
    problema ou alcançar um objetivo.
  </li>
  <li>
    Uma condição ou capacidade que deve ser atendida ou possuída por uma solução
    (ou componente dela) para satisfazer um contrato, padrão ou especificação
    formal.
  </li>
  <li>A representação documentada de uma dessas condições ou capacidades.</li>
</ol>

<h3>Técnicas de Análise de Negócios</h3>

<p>
  As técnicas alteram a forma como uma tarefa é desempenhada ou descrevem o
  formato específico de uma entrega. Entre as técnicas utilizadas regularmente
  pelos analistas, destacam-se:
</p>

<ul>
  <li>Definição de critérios de aceite e avaliação.</li>
  <li>Brainstorming.</li>
  <li>
    Dicionário de dados, glossário, diagramas de fluxo de dados e modelagem de
    dados.
  </li>
  <li>Análise de decisão e de documentos.</li>
  <li>Entrevistas, workshops de requisitos, cenários e casos de uso.</li>
  <li>Métricas e indicadores-chave de desempenho.</li>
  <li>Análise de requisitos não funcionais.</li>
  <li>Modelagem da organização e rastreamento de problemas.</li>
  <li>Modelagem de processos.</li>
</ul>

<h3>Aplicações de Técnicas Específicas</h3>

<ul>
  <li>
    <strong>Análise de regras de negócio:</strong> Identifica requisitos e definições.
  </li>
  <li>
    <strong>Diagramas de fluxo de dados:</strong> Identificam o modelo mais apropriado.
  </li>
  <li>
    <strong>Decomposição funcional:</strong> Auxilia na compreensão dos processos
    e componentes da solução.
  </li>
  <li><strong>Modelagem organizacional:</strong> Organiza os requisitos.</li>
</ul>

<h3>Contexto Estratégico, Tático e Operacional</h3>

<p>
  A análise corporativa engloba a identificação de problemas e oportunidades, a
  avaliação das capacidades da organização, a identificação das necessidades do
  negócio, a definição da abordagem para atendê-las e a definição do escopo da
  solução. O objetivo é compreender a organização para aumentar a sua
  eficiência.
</p>

<h3>Níveis de Análise de Negócios</h3>

<h4>Contexto Estratégico</h4>

<p>
  Foca em compreender os rumos da organização e quais oportunidades ela irá
  aproveitar. Desenvolve-se um pré-projeto para identificar os problemas,
  definir oportunidades, estruturar um caso de negócios e recomendar ou não o
  início de um projeto.
</p>

<h4>Contexto Tático</h4>

<p>
  Tem como alvo o nível do projeto e a execução dos planos, aproximando-se da
  função tradicional do analista de negócios baseada na observação do sistema.
  Impacta a empresa diretamente no momento da análise e no nível de detalhe do
  resultado.
</p>

<h4>Contexto Operacional</h4>

<p>
  É o nível focado em tecnologia, informações, fluxos de trabalho e no "como
  fazer". Utiliza os requisitos das partes interessadas em seu sentido
  tradicional de funcionalidade e qualidade.
</p>

<h3>Técnicas no Nível Operacional</h3>

<p>
  As técnicas aplicadas no nível operacional utilizam os objetos de evento,
  interface e operadores lógicos. Essa combinação permite registrar o fluxo de
  trabalho de forma complexa e fiel à realidade da operação, englobando:
</p>

<ul>
  <li>Entradas e saídas.</li>
  <li>Resultados intermediários.</li>
  <li>Decisões e caminhos alternativos.</li>
</ul>

<h3>Métodos de Análise de Negócios</h3>

<p>
  A análise de negócios atua como um facilitador de mudanças nas empresas,
  definindo necessidades e recomendando soluções que agregam valor às partes
  interessadas.
</p>

<h4>Motivos para Utilizar a Análise de Negócios</h4>

<ul>
  <li>Compreender a estrutura e a dinâmica da empresa.</li>
  <li>Entender os problemas atuais da organização.</li>
  <li>Identificar potenciais melhorias.</li>
  <li>Recomendar soluções para o alcance de metas.</li>
  <li>Identificar e articular a necessidade de mudança.</li>
  <li>Maximizar o valor entregue aos stakeholders.</li>
</ul>

<h4>Etapas da Análise de Negócios</h4>

<ul>
  <li>Análise empresarial.</li>
  <li>Planejamento e gerenciamento de requisitos.</li>
  <li>Elicitação de requisitos.</li>
  <li>Análise de requisitos e documentação.</li>
  <li>Comunicação de requisitos.</li>
  <li>Evolução e validação da solução.</li>
</ul>

<h3>Técnicas Mais Comuns de Análise de Negócios</h3>

<ul>
  <li>
    <strong>MOST (Missão, Objetivos e Estratégias):</strong> Permite realizar análises
    internas completas sobre o objetivo da organização e como conduzi-lo.
  </li>
  <li>
    <strong
      >PESTLE (Política, Economia, Social, Tecnologia, Legalidade e Meio
      Ambiente):</strong
    >
    Auxilia na avaliação de fatores externos que impactam a organização e na definição
    de como resolvê-los.
  </li>
  <li>
    <strong>SWOT (Forças, Fraquezas, Oportunidades e Ameaças):</strong> Identifica
    as áreas de força e fraqueza para a alocação adequada de recursos.
  </li>
  <li>
    <strong
      >MoSCoW (Deve, Deveria, Poderia ou Seria - Must, Should, Could, Won't):</strong
    >
    Prioriza requisitos por meio de uma estrutura de avaliação mútua.
  </li>
  <li>
    <strong>
      CATWOE (Clientes, Atores, Processo de transformação, Visão mundial,
      Proprietário e Meio ambiente):
    </strong> Reconhece os processos que podem ser afetados por ações da empresa.
  </li>
  <li>
    <strong>5 Porquês:</strong> Técnica que destaca a causa-raiz de um problema ao
    perguntar sucessivamente "por que" a situação ocorre.
  </li>
  <li>
    <strong>Seis Chapéus do Pensamento:</strong> Técnica que considera
    perspectivas alternativas divididas em seis abordagens direcionadas:
    <ul>
      <li><strong>Verde:</strong> Pensamento criativo.</li>
      <li><strong>Azul:</strong> Visão geral.</li>
      <li><strong>Branco:</strong> Pensamento lógico e orientado a dados.</li>
      <li>
        <strong>Amarelo:</strong> Pensamento positivo, focado nos profissionais.
      </li>
      <li><strong>Vermelho:</strong> Reações baseadas na emoção.</li>
      <li>
        <strong>Preto:</strong> Pensamento oposto, focado no contra-argumento.
      </li>
    </ul>
  </li>
</ul>

<h3>Conclusão</h3>

<ul>
  <li>
    <strong>Processos como núcleo:</strong> Os processos estão presentes em todos
    os departamentos e equipes, sendo pontos críticos para o sucesso das operações.
  </li>
  <li>
    <strong>O papel do To Be:</strong> O mapeamento to be foca em melhorias de ruptura
    ou no atendimento de demandas de mercado, normativas e estratégias da empresa.
  </li>
  <li>
    <strong>Função da análise de negócios:</strong> Envolve pesquisa para identificar
    necessidades corporativas, criar soluções para problemas e permitir mudanças
    que agreguem valor às partes interessadas.
  </li>
  <li>
    <strong>Objetivo da análise corporativa:</strong> Compreender a organização,
    ou parte dela, para identificar necessidades que devem ser satisfeitas para o
    aumento da eficiência do negócio.
  </li>
</ul>
